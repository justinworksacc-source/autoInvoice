import { database, ensureCompany } from "../server/db.js";
import { body, fail, json, requireRole, requireSession } from "../server/security.js";

const statuses = new Set(["scheduled", "in_progress", "completed", "cancelled"]);

async function ensureSchema() {
  await ensureCompany();
  await database().execute(
    `CREATE TABLE IF NOT EXISTS field_service_jobs (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      company_id BIGINT NOT NULL REFERENCES companies(id),
      customer_name VARCHAR(255) NOT NULL,
      service_address VARCHAR(500) NOT NULL,
      title VARCHAR(255) NOT NULL,
      description TEXT,
      scheduled_at TIMESTAMPTZ,
      assigned_to BIGINT REFERENCES auth_accounts(id) ON DELETE SET NULL,
      status VARCHAR(30) NOT NULL DEFAULT 'scheduled',
      technician_notes TEXT,
      created_by BIGINT REFERENCES auth_accounts(id) ON DELETE SET NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    )`
  );
  await database().execute(
    "CREATE INDEX IF NOT EXISTS field_service_jobs_assignment_idx ON field_service_jobs (company_id,assigned_to,status,scheduled_at)"
  );
}

async function readJobs(session) {
  const technicianFilter = session.role === "technician" ? " AND j.assigned_to=?" : "";
  const values = session.role === "technician" ? [session.userId] : [];
  const [jobs] = await database().execute(
    `SELECT j.id,j.customer_name AS "customerName",j.service_address AS "serviceAddress",
      j.title,COALESCE(j.description,'') AS description,
      COALESCE(TO_CHAR(j.scheduled_at AT TIME ZONE 'Asia/Manila','YYYY-MM-DD\"T\"HH24:MI'),'') AS "scheduledAt",
      j.assigned_to AS "assignedTo",COALESCE(a.full_name,a.username,'Unassigned') AS "assignedName",
      j.status,COALESCE(j.technician_notes,'') AS "technicianNotes",
      TO_CHAR(j.updated_at AT TIME ZONE 'Asia/Manila','YYYY-MM-DD HH24:MI') AS "updatedAt"
     FROM field_service_jobs j LEFT JOIN auth_accounts a ON a.id=j.assigned_to
     WHERE j.company_id=1${technicianFilter}
     ORDER BY CASE j.status WHEN 'in_progress' THEN 0 WHEN 'scheduled' THEN 1 WHEN 'completed' THEN 2 ELSE 3 END,
       j.scheduled_at NULLS LAST,j.id DESC`,
    values
  );
  const [technicians] = session.role === "technician" ? [[]] : await database().execute(
    `SELECT id,COALESCE(full_name,username) AS name,username FROM auth_accounts
     WHERE company_id=1 AND role='technician' AND is_active=TRUE ORDER BY COALESCE(full_name,username)`
  );
  return { jobs, technicians };
}

export default async function handler(req, res) {
  try {
    const session = requireSession(req);
    requireRole(session, ["admin", "technician"]);
    await ensureSchema();
    if (req.method === "GET") return json(res, 200, { success: true, ...(await readJobs(session)) });
    if (req.method !== "POST") return json(res, 405, { success: false, error: "Method not allowed." });
    const input = await body(req);
    if (input.action === "create") {
      requireRole(session, ["admin"]);
      const customerName = String(input.customer_name || "").trim();
      const address = String(input.service_address || "").trim();
      const title = String(input.title || "").trim();
      const assignedTo = Number(input.assigned_to) || null;
      if (!customerName || !address || !title) throw Object.assign(new Error("Customer, service address, and job title are required."), { status: 422 });
      if (assignedTo) {
        const [[technician]] = await database().execute(
          "SELECT COUNT(*)::int AS count FROM auth_accounts WHERE id=? AND company_id=1 AND role='technician' AND is_active=TRUE",
          [assignedTo]
        );
        if (!technician.count) throw Object.assign(new Error("Choose an active technician."), { status: 422 });
      }
      await database().execute(
        `INSERT INTO field_service_jobs
          (company_id,customer_name,service_address,title,description,scheduled_at,assigned_to,created_by)
         VALUES (1,?,?,?,?,NULLIF(?,'')::timestamp AT TIME ZONE 'Asia/Manila',?,?)`,
        [customerName, address, title, String(input.description || "").trim() || null,
          String(input.scheduled_at || ""), assignedTo, session.userId]
      );
    } else if (input.action === "update") {
      const id = Number(input.job_id);
      const status = String(input.status || "");
      if (!id || !statuses.has(status)) throw Object.assign(new Error("A valid job and status are required."), { status: 422 });
      const roleFilter = session.role === "technician" ? " AND assigned_to=?" : "";
      const values = [status, String(input.technician_notes || "").trim() || null, id];
      if (session.role === "technician") values.push(session.userId);
      const [result] = await database().execute(
        `UPDATE field_service_jobs SET status=?,technician_notes=?,updated_at=NOW()
         WHERE id=? AND company_id=1${roleFilter}`,
        values
      );
      if (!result.affectedRows) throw Object.assign(new Error("Field-service job was not found or is not assigned to you."), { status: 404 });
    } else if (input.action === "assign") {
      requireRole(session, ["admin"]);
      const id = Number(input.job_id);
      const assignedTo = Number(input.assigned_to) || null;
      if (assignedTo) {
        const [[technician]] = await database().execute(
          "SELECT COUNT(*)::int AS count FROM auth_accounts WHERE id=? AND company_id=1 AND role='technician' AND is_active=TRUE",
          [assignedTo]
        );
        if (!technician.count) throw Object.assign(new Error("Choose an active technician."), { status: 422 });
      }
      await database().execute("UPDATE field_service_jobs SET assigned_to=?,updated_at=NOW() WHERE id=? AND company_id=1", [assignedTo, id]);
    } else {
      throw Object.assign(new Error("Unknown field-service operation."), { status: 422 });
    }
    return json(res, 200, { success: true, ...(await readJobs(session)) });
  } catch (error) {
    return fail(res, error);
  }
}
