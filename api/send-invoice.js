import PDFDocument from "pdfkit";
import { body, fail, json, requireSession } from "../server/security.js";

function text(value, fallback = "") {
  return String(value || fallback).trim();
}

function createInvoicePdf(invoice) {
  return new Promise((resolve, reject) => {
    const document = new PDFDocument({ size: "A4", margin: 50, info: {
      Title: `Invoice ${text(invoice.invoice_number)}`,
      Author: text(invoice.company_name, "Visual Security Systems")
    } });
    const chunks = [];
    document.on("data", (chunk) => chunks.push(chunk));
    document.on("end", () => resolve(Buffer.concat(chunks)));
    document.on("error", reject);

    const company = text(invoice.company_name, "Visual Security Systems");
    const invoiceNumber = text(invoice.invoice_number);
    const customer = text(invoice.to_name, text(invoice.to));
    const address = text(invoice.customer_address);

    document.fillColor("#071a3d").fontSize(22).font("Helvetica-Bold").text(company);
    document.moveDown(0.25).fillColor("#48556a").fontSize(10).font("Helvetica")
      .text(text(invoice.from_alias), { continued: false });
    document.moveDown(2);

    document.fillColor("#111827").fontSize(28).font("Helvetica-Bold").text("INVOICE");
    document.moveDown(0.3).fontSize(11).font("Helvetica")
      .text(`Invoice number: ${invoiceNumber}`)
      .text(`Due date: ${text(invoice.due_date)}`);

    document.moveDown(2).fillColor("#071a3d").fontSize(11).font("Helvetica-Bold").text("BILL TO");
    document.moveDown(0.35).fillColor("#111827").fontSize(12).text(customer);
    document.font("Helvetica").fontSize(10).text(text(invoice.to));
    if (address) document.text(address);

    const tableTop = document.y + 32;
    document.rect(50, tableTop, 495, 30).fill("#071a3d");
    document.fillColor("#ffffff").font("Helvetica-Bold").fontSize(10)
      .text("DESCRIPTION", 62, tableTop + 10)
      .text("AMOUNT", 445, tableTop + 10, { width: 88, align: "right" });

    const rowTop = tableTop + 30;
    document.rect(50, rowTop, 495, 42).fill("#f3f7fc");
    document.fillColor("#111827").font("Helvetica").fontSize(10)
      .text(`Monthly service charge · Billing day ${text(invoice.billing_day)}`, 62, rowTop + 15)
      .text(text(invoice.monthly_amount, "0.00"), 445, rowTop + 15, { width: 88, align: "right" });

    let summaryY = rowTop + 92;
    const summaryLine = (label, value, bold = false) => {
      document.fillColor("#374151").font(bold ? "Helvetica-Bold" : "Helvetica").fontSize(bold ? 12 : 10)
        .text(label, 315, summaryY, { width: 130 })
        .text(value, 445, summaryY, { width: 88, align: "right" });
      summaryY += bold ? 26 : 20;
    };
    summaryLine("Previous balance", text(invoice.previous_balance, "0.00"));
    document.moveTo(315, summaryY - 5).lineTo(533, summaryY - 5).strokeColor("#cbd5e1").stroke();
    summaryLine("TOTAL DUE", text(invoice.amount, "0.00"), true);

    document.y = summaryY + 30;
    document.fillColor("#071a3d").font("Helvetica-Bold").fontSize(10).text("PAYMENT REFERENCE");
    document.moveDown(0.35).fillColor("#111827").font("Helvetica").fontSize(11).text(invoiceNumber);

    document.moveDown(3).fillColor("#64748b").fontSize(9)
      .text(`Please use ${invoiceNumber} as your payment reference. Thank you for your business.`);
    document.moveDown(0.5).text(`Generated by ${company}.`);

    document.end();
  });
}

export default async function handler(req, res) {
  try {
    requireSession(req);
    if (req.method !== "POST") return json(res, 405, { success: false, error: "Method not allowed." });
    const invoice = await body(req);
    if (!invoice.to || !invoice.invoice_number) throw Object.assign(new Error("Recipient and invoice number are required."), { status: 422 });
    const webhook = process.env.SEND_INVOICE_WEBHOOK_URL;
    if (!webhook) throw Object.assign(new Error("Set SEND_INVOICE_WEBHOOK_URL in Vercel to enable invoice delivery."), { status: 503 });
    const invoicePdf = await createInvoicePdf(invoice);
    const attachment = {
      content_base64: invoicePdf.toString("base64"),
      content_type: "application/pdf",
      file_name: `${text(invoice.invoice_number, "invoice").replace(/[^a-zA-Z0-9._-]/g, "_")}.pdf`
    };
    const response = await fetch(webhook, {
      method: "POST",
      headers: { "Content-Type": "application/json", "X-Webhook-Secret": process.env.SEND_INVOICE_SECRET || "" },
      body: JSON.stringify({ secret: process.env.SEND_INVOICE_SECRET || "", invoice, attachment })
    });
    const result = await response.json().catch(() => ({}));
    if (!response.ok || result.success === false) throw Object.assign(new Error(result.error || "Invoice delivery webhook failed."), { status: 502 });
    return json(res, 200, { success: true, delivery: result.delivery || "webhook", message_id: result.message_id || null });
  } catch (error) {
    return fail(res, error);
  }
}
